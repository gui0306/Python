''' Dobro, triplo e metade '''

numero = int(input("Digite um número inteiro: "))

numeroD = 2 * numero
numeroT = 3 * numero
numeroM = numero / 2

print(f'O numero coletado foi: {numero}')
print(f'O dobro do número é: {numeroD}')
print(f'O triplo do número é: {numeroT}')
print(f'A metade do número é: {numeroM}')
